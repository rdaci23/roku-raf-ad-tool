import type { RafPlaybackMode, RafRuntimePrefs } from './types.js';

export interface BrsGeneratorInput {
  mode: RafPlaybackMode;
  adTagOrStreamUrl: string;
  contentUrl?: string;
  ssaiMetaUrl?: string;
  prefs: RafRuntimePrefs;
}

export function generateBrightScriptSnippet(input: BrsGeneratorInput): string {
  const { mode, adTagOrStreamUrl, prefs } = input;
  const contentUrl = input.contentUrl || 'https://cdn.example.com/content/episode-101.m3u8';
  const resMap: Record<RafRuntimePrefs['maxResolution'], [number, number]> = {
    '720p': [1280, 720],
    '1080p': [1920, 1080],
    '4k': [3840, 2160],
  };
  const [maxW, maxH] = resMap[prefs.maxResolution];

  const header = `' Generated by Roku RAF Ad Tool — SceneGraph Task Component
Library "Roku_Ads.brs"

sub runRafAdFlow(videoNode as Object)
    raf = Roku_Ads()
    raf.setDebugOutput(true)
    raf.enableAdMeasurements(${prefs.enableAdMeasurements ? 'true' : 'false'})
    raf.setAdPrefs(${prefs.useRokuAdsFallback ? 'true' : 'false'}, ${prefs.maxRequests})
    if videoNode.hasField("maxVideoDecodeResolution")
        videoNode.maxVideoDecodeResolution = [${maxW}, ${maxH}]
    end if

    ' Required content metadata for Nielsen / OMID / Roku Certification
    raf.setContentId("${prefs.contentId.replace(/"/g, '')}")
    raf.setContentGenre("${prefs.contentGenre.replace(/"/g, '')}")
    raf.setContentLength(${prefs.contentLengthSec})

    ' Verify RIDA & Limit Ad Tracking state via roDeviceInfo
    devInfo = CreateObject("roDeviceInfo")
    isLat = devInfo.IsRIDADisabled()
    rida = devInfo.GetRIDA()
    if isLat then rida = "00000000-0000-0000-0000-000000000000"
`;

  if (mode === 'csai-stitched') {
    return `${header}
    ' Mode: Client-Stitched Stream (raf.constructStitchedStream + raf.renderStitchedStream)
    raf.setAdUrl("${adTagOrStreamUrl}")
    adPods = raf.getAds()

    contentNode = CreateObject("roSGNode", "ContentNode")
    contentNode.url = "${contentUrl}"
    contentNode.streamFormat = "${contentUrl.endsWith('.m3u8') ? 'hls' : 'mp4'}"
    contentNode.title = "${prefs.contentId}"
    contentNode.length = ${prefs.contentLengthSec}

    viewNode = videoNode.getParent()
    stitchedStream = raf.constructStitchedStream(contentNode, adPods)
    completedFull = raf.renderStitchedStream(stitchedStream, viewNode)
    print "[RAF] Client-stitched playback finished. completed=" ; completedFull
end sub
`;
  }

  if (mode === 'csai-skippable') {
    return `${header}
    ' Mode: Custom SceneGraph Skippable VAST Ad Overlay (solves roku_ads_lib showAds() ignoring skipoffset)
    ' Expects skipOverlay Group + skipLabel Label in MainScene and m.top.skipRequested boolean field on Task
    http = CreateObject("roUrlTransfer")
    http.SetCertificatesFile("common:/certs/ca-bundle.crt")
    http.InitClientCertificates()
    http.SetUrl("${adTagOrStreamUrl}")
    rawVast = http.GetToString()

    skipOffsetSec = 5
    rxSkip = CreateObject("roRegex", "skipoffset\\s*=\\s*""(\\d+):(\\d+):(\\d+)""", "i")
    mSkip = rxSkip.Match(rawVast)
    if mSkip.Count() >= 4
        skipOffsetSec = mSkip[1].ToInt() * 3600 + mSkip[2].ToInt() * 60 + mSkip[3].ToInt()
    end if

    raf.setAdUrl("${adTagOrStreamUrl}")
    adPods = raf.getAds()
    if adPods <> invalid and adPods.Count() > 0 and adPods[0].ads <> invalid and adPods[0].ads.Count() > 0
        spot = adPods[0].ads[0]
        adContent = CreateObject("roSGNode", "ContentNode")
        adContent.url = spot.streams[0].url
        adContent.streamFormat = "mp4"

        port = CreateObject("roMessagePort")
        m.top.observeFieldScoped("skipRequested", port)
        videoNode.enableUI = false
        videoNode.content = adContent
        videoNode.observeFieldScoped("position", port)
        videoNode.observeFieldScoped("state", port)
        m.top.skipOverlayNode.visible = true
        m.top.skipOverlayNode.setFocus(true)
        videoNode.control = "play"

        while true
            msg = wait(250, port)
            if m.top.skipRequested = true
                videoNode.control = "stop"
                ' Fire VAST <Tracking event="skip"> & <Tracking event="closeLinear"> beacons; suppress remaining quartiles
                for each trk in spot.tracking
                    if LCase(trk.event) = "skip" or LCase(trk.event) = "closelinear"
                        b = CreateObject("roUrlTransfer")
                        b.SetCertificatesFile("common:/certs/ca-bundle.crt")
                        b.InitClientCertificates()
                        b.SetUrl(trk.url)
                        b.GetToString()
                    end if
                end for
                exit while
            else if type(msg) = "roSGNodeEvent" and msg.getField() = "position"
                playPos = videoNode.position
                if playPos >= skipOffsetSec
                    m.top.canSkipNow = true
                    m.top.skipLabelNode.text = "Press OK to Skip Ad >>"
                else
                    m.top.skipLabelNode.text = "Skip Ad in " + Int(skipOffsetSec - playPos + 0.99).ToStr() + "s"
                end if
            else if type(msg) = "roSGNodeEvent" and msg.getField() = "state"
                if msg.getData() = "finished" or msg.getData() = "error" then exit while
            end if
        end while
        m.top.skipOverlayNode.visible = false
        videoNode.enableUI = true
    end if
end sub
`;
  }

  if (mode === 'ssai' || mode === 'ssai-live') {
    const metaUrl = input.ssaiMetaUrl || 'https://ssai.example.com/session/raf-metadata.json';
    return `${header}
    ' Mode: ${mode === 'ssai-live' ? 'Live Linear HLS SSAI' : 'VOD Stitched SSAI'} (raf.stitchedAdsInit + raf.stitchedAdHandledEvent)
    http = CreateObject("roUrlTransfer")
    http.SetCertificatesFile("common:/certs/ca-bundle.crt")
    http.InitClientCertificates()
    http.SetUrl("${metaUrl}")
    adPods = ParseJson(http.GetToString())
    if adPods <> invalid then raf.stitchedAdsInit(adPods)

    port = CreateObject("roMessagePort")
    content = CreateObject("roSGNode", "ContentNode")
    content.url = "${adTagOrStreamUrl}"
    content.streamFormat = "hls"
    ${mode === 'ssai-live' ? 'content.live = true' : ''}

    videoNode.content = content
    videoNode.observeFieldScoped("position", port)
    videoNode.observeFieldScoped("state", port)
    videoNode.observeFieldScoped("timedMetaData", port)
    videoNode.setFocus(true)
    videoNode.control = "play"

    player = { sgNode: videoNode, port: port }
    while true
        msg = wait(500, port)
        if msg <> invalid
            curAd = raf.stitchedAdHandledEvent(msg, player)
            if curAd <> invalid and curAd.adExited = true then exit while
            if type(msg) = "roSGNodeEvent" and msg.getField() = "state"
                st = msg.getData()
                if st = "finished" or st = "error" then exit while
            end if
        end if
    end while
end sub
`;
  }

  if (mode === 'google-dai') {
    return `${header}
    ' Mode: Google Ad Manager DAI Stream Session Bootstrap + RAF Stitched Playback
    daiPort = CreateObject("roMessagePort")
    daiReq = CreateObject("roUrlTransfer")
    daiReq.SetMessagePort(daiPort)
    daiReq.SetCertificatesFile("common:/certs/ca-bundle.crt")
    daiReq.InitClientCertificates()
    daiReq.SetUrl("${adTagOrStreamUrl}")
    daiReq.AddHeader("Content-Type", "application/x-www-form-urlencoded")

    latStr = "0"
    if isLat then latStr = "1"
    postBody = "rdid=" + rida + "&idtype=rida&is_lat=" + latStr
    rawDaiJson = ""
    if daiReq.AsyncPostFromString(postBody)
        daiEv = wait(8000, daiPort)
        if type(daiEv) = "roUrlEvent" and daiEv.GetResponseCode() >= 200 and daiEv.GetResponseCode() < 300
            rawDaiJson = daiEv.GetString()
        end if
    end if
    sessionResp = invalid
    if rawDaiJson <> "" then sessionResp = ParseJson(rawDaiJson)
    if sessionResp = invalid or sessionResp.stream_manifest = invalid then return

    if sessionResp.ad_pods <> invalid
        raf.stitchedAdsInit(sessionResp.ad_pods)
    end if

    port = CreateObject("roMessagePort")
    content = CreateObject("roSGNode", "ContentNode")
    content.url = sessionResp.stream_manifest
    content.streamFormat = "hls"

    videoNode.content = content
    videoNode.observeFieldScoped("position", port)
    videoNode.observeFieldScoped("state", port)
    videoNode.setFocus(true)
    videoNode.control = "play"

    player = { sgNode: videoNode, port: port }
    while true
        msg = wait(500, port)
        if msg <> invalid
            curAd = raf.stitchedAdHandledEvent(msg, player)
            if curAd <> invalid and curAd.adExited = true then exit while
            if type(msg) = "roSGNodeEvent" and msg.getField() = "state"
                if msg.getData() = "finished" or msg.getData() = "error" then exit while
            end if
        end if
    end while
end sub
`;
  }

  // Default: Standard CSAI (getAds + showAds + Midroll/Postroll observer loop)
  return `${header}
    ' Mode: Standard CSAI (raf.getAds + raf.showAds for Preroll, Midroll & Postroll)
    raf.setAdUrl("${adTagOrStreamUrl}")
    adPods = raf.getAds()
    viewNode = videoNode.getParent()

    shouldPlayContent = true
    if adPods <> invalid and adPods.Count() > 0
        shouldPlayContent = raf.showAds(adPods, invalid, viewNode)
    end if
    if not shouldPlayContent then return

    port = CreateObject("roMessagePort")
    content = CreateObject("roSGNode", "ContentNode")
    content.url = "${contentUrl}"
    content.streamFormat = "${contentUrl.endsWith('.m3u8') ? 'hls' : 'mp4'}"

    videoNode.content = content
    videoNode.observeFieldScoped("position", port)
    videoNode.observeFieldScoped("state", port)
    videoNode.setFocus(true)
    videoNode.control = "play"

    while true
        msg = wait(500, port)
        if type(msg) = "roSGNodeEvent"
            field = msg.getField()
            if field = "position"
                midPods = raf.getAds(msg)
                if midPods <> invalid and midPods.Count() > 0
                    resumePos = videoNode.position
                    videoNode.control = "stop"
                    if raf.showAds(midPods, invalid, viewNode)
                        videoNode.seek = resumePos
                        videoNode.control = "play"
                    else
                        exit while
                    end if
                end if
            else if field = "state" and msg.getData() = "finished"
                postPods = raf.getAds(msg)
                if postPods <> invalid and postPods.Count() > 0
                    raf.showAds(postPods, invalid, viewNode)
                end if
                exit while
            end if
        end if
    end while
end sub
`;
}
